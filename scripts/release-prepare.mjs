import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { captureAudit, validateAudit } from "./audit-evidence.mjs";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const npmCli = process.env.npm_execpath;
assert.ok(npmCli, "run through npm run release:prepare");
const run = (command, args) => {
  const result = spawnSync(command, args, { cwd: root, encoding: "utf8", timeout: 180_000, maxBuffer: 32 * 1024 * 1024 });
  if (result.error || result.status !== 0) throw new Error(`Release preparation command failed: ${args[0]}`);
  return result.stdout;
};
const npm = (args) => run(process.execPath, [npmCli, ...args]);
const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const status = JSON.parse(readFileSync(join(root, "release-status.json"), "utf8"));
assert.equal(status.version, pkg.version);
const commit = run("git", ["rev-parse", "HEAD"]).trim();
assert.equal(run("git", ["status", "--porcelain"]).trim(), "", "Commit the reviewed candidate before generating release evidence");
const output = join(root, "release-artifacts", `${pkg.version}-${commit.slice(0, 12)}-${Date.now()}`);
mkdirSync(output, { recursive: true });
const json = (name, value) => writeFileSync(join(output, name), JSON.stringify(value, null, 2) + "\n");
const audit = captureAudit({ npmCli, cwd: root, omitDev: true });
json("production-audit.json", audit);
assert.equal(validateAudit(audit).total, 0, "Candidate gate requires zero production advisories");
const sbom = JSON.parse(npm(["sbom", "--omit=dev", "--sbom-format", "cyclonedx"]));
assert.equal(sbom.bomFormat, "CycloneDX");
json("sbom.cdx.json", sbom);
const packed = JSON.parse(npm(["pack", "--json", "--pack-destination", output]));
assert.equal(packed.length, 1);
assert.equal(packed[0].version, pkg.version);
const tarball = packed[0].filename;
assert.equal(tarball, `${pkg.name}-${pkg.version}.tgz`);
const hash = () => createHash("sha256").update(readFileSync(join(output, tarball))).digest("hex");
const sha256 = hash();
npm(["pack", "--json", "--pack-destination", output]);
assert.equal(hash(), sha256, "Two consecutive pack operations must produce identical bytes");
json("pack.json", packed[0]);
json("release-status.json", status);
const metadata = { kind: "erascript-local-release-candidate", name: pkg.name, version: pkg.version, commit, node: process.version, generatedAt: new Date().toISOString(), tarball, sha256, reproduciblePack: true, productionAdvisories: validateAudit(audit), publicationApproved: false, scope: "Local candidate for review; not production approval", blockers: status.blockers };
json("candidate.json", metadata);
writeFileSync(join(output, "SHA256SUMS"), `${sha256}  ${tarball}\n`);
console.log(JSON.stringify({ output, ...metadata }, null, 2));
